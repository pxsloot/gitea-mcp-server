"""Shared agent-facing contract for manually registered synthetic tools.

Autogenerated tools receive validation and pagination behaviour from the
server-level contract transform. Synthetic tools are registered on the root
server and stamp the same ``_contract_wrap`` marker, so the transform wraps
them identically: virtual-param injection/extraction (from the
:mod:`virtual_params` registry), validation, pagination metadata, and
post-hoc formatting all flow through one shared spine
(:func:`~tools.contract.build_transform_fn`).

This module provides the registration-side contract:

- :func:`make_impl_executor` builds the per-tool executor the transform runs
  for a synthetic tool.  It re-supplies popped virtual params to the impl
  (which still declares them — including tool-specific params that collide
  with registry names, e.g. ``tool_info``'s ``detail``), validates
  ``page``/``limit`` for paginated tools, calls the impl, and marks the
  result ``_formatted`` so the shared format post-hook does not re-render
  the impl's own formatting.
- :class:`SyntheticToolSpec` is the declarative registration unit: one
  dataclass per tool carrying the impl, ``mcp.tool()`` options, and the
  contract knobs (``paginated``, ``limit_max``, ``virtual_params``,
  ``required_scope``, ``wrap``).  Modules build their spec lists where their
  implementation closures live and hand them to
  :func:`register_all_synthetic_tools` — no hand-rolled per-call wrapper
  options.
- :func:`register_synthetic_tool` stamps the wrap marker + a serializable
  ``_executor_id`` (the executor itself lives in the server's registry — a
  callable in ``tool.meta`` raises ``PydanticSerializationError``) + the
  tool's virtual-param allowlist into ``tool.meta``, declares the pagination
  envelope in ``output_schema``, and declares the per-tool ``limit`` bound.

API execution and HTTP error handling remain backend concerns — the
executor is backend-neutral.
"""

from __future__ import annotations

import copy
import inspect
from dataclasses import dataclass
from typing import TYPE_CHECKING, Annotated, Any, cast, get_args, get_origin
from weakref import WeakKeyDictionary

if TYPE_CHECKING:
    from collections.abc import Callable, Iterable

    from fastmcp.tools.base import ToolResult

    from gitea_mcp_server.tools.contract import Executor

from pydantic import Field

from gitea_mcp_server.constants import PAGE_SIZE_MAX
from gitea_mcp_server.pagination import PAGINATION_SCHEMA_PROPERTIES
from gitea_mcp_server.validation import validate_pagination


class SyntheticExecutorRegistry:
    """Per-server registry of synthetic executors.

    Executors cannot live in ``tool.meta`` — FastMCP pydantic-serializes meta
    (a callable raises ``PydanticSerializationError``).  Instead each server's
    executors live in a registry scoped to that server and released with it;
    ``tool.meta`` carries only the serializable ``_executor_id`` (the tool's
    unprefixed registration name, unique within one server).
    """

    def __init__(self) -> None:
        self._executors: dict[str, Executor] = {}

    def register(self, name: str, executor: Executor) -> None:
        """Store *executor* under *name* (the tool's unprefixed registration name)."""
        self._executors[name] = executor

    def get(self, name: str | None) -> Executor | None:
        """Return the executor registered under *name*, or ``None``."""
        if name is None:
            return None
        return self._executors.get(name)


# One registry per FastMCP server, keyed weakly by the server instance so a
# server's executors are released when the server is garbage-collected
# (tests, hot-reload) — no unbounded accumulation across server instances in
# one process.  Per-server scoping also means the same tool name on two
# servers can never resolve to another server's executor closure.
_SERVER_REGISTRIES: WeakKeyDictionary[Any, SyntheticExecutorRegistry] = WeakKeyDictionary()


def get_executor_registry(mcp: Any) -> SyntheticExecutorRegistry:
    """Return the per-server synthetic executor registry for *mcp*, creating it lazily.

    Args:
        mcp: The FastMCP server instance the registry belongs to.

    Returns:
        The server's registry.  The same server always returns the same
        registry; a different server gets its own.
    """
    registry = _SERVER_REGISTRIES.get(mcp)
    if registry is None:
        registry = SyntheticExecutorRegistry()
        _SERVER_REGISTRIES[mcp] = registry
    return registry


@dataclass
class SyntheticToolSpec:
    """Declarative registration spec for one synthetic tool.

    Built at registration time inside a module's ``register_*`` function
    (where the implementation closure lives — the impl captures deps such as
    the search transform, doc manager, or OpenAPI spec) and processed by
    :func:`register_all_synthetic_tools`.

    Attributes:
        impl: The synthetic tool function.  Its signature (including
            declared ``format``/``detail``/``fetch_all``/``ctx``) defines the
            agent-facing schema; its body performs the real work.
        name: Tool name.  Defaults to ``impl.__name__``.
        description: Tool description.  Defaults to FastMCP's docstring
            derivation.
        tags: Tool tags (``"synthetic"`` plus a domain tag).
        annotations: Tool annotations (use
            :func:`~gitea_mcp_server.tools.customize.synthetic_annotations`).
        output_schema: JSON Schema for the tool result envelope.
        paginated: Validate ``page``/``limit`` at runtime and declare the
            pagination envelope in ``output_schema``.
        limit_max: Upper bound for ``limit`` (defaults to ``PAGE_SIZE_MAX``).
        virtual_params: Allowlist of registry virtual params this tool opts
            into.  Defaults to ``{"format", "detail", "fetch_all"}`` for
            paginated tools, ``{"format", "detail"}`` otherwise.  Tool-
            specific profiles pass their own set; ``sudo`` is opt-in.
        required_scope: Optional Gitea API scope required to use this tool.
            Stamped in ``tool.meta`` for future scope gating of synthetic
            tools (mirrors ``ResourceMeta.required_scope``); currently no
            synthetic tool declares one.
        wrap: When ``True`` (default), ride the server-level contract
            transform.  Set ``False`` for proxy tools that must pass
            arguments through untouched (``call_tool``).
    """

    impl: Callable[..., Any]
    name: str | None = None
    description: str | None = None
    tags: set[str] | None = None
    annotations: Any | None = None
    output_schema: dict[str, Any] | None = None
    paginated: bool = False
    limit_max: int | None = None
    virtual_params: set[str] | None = None
    required_scope: str | None = None
    wrap: bool = True

    def tool_options(self) -> dict[str, Any]:
        """Return the ``mcp.tool()`` options this spec declares (non-None)."""
        options: dict[str, Any] = {}
        if self.name is not None:
            options["name"] = self.name
        if self.description is not None:
            options["description"] = self.description
        if self.tags is not None:
            options["tags"] = self.tags
        if self.annotations is not None:
            options["annotations"] = self.annotations
        if self.output_schema is not None:
            options["output_schema"] = self.output_schema
        return options


def register_all_synthetic_tools(
    mcp: Any,
    specs: Iterable[SyntheticToolSpec],
) -> None:
    """Register every synthetic tool spec through the shared contract.

    Wrapped specs (``wrap=True``) ride the server-level contract transform
    via :func:`register_synthetic_tool` — the executor is built from the
    spec's impl, and the tool is stamped with the wrap marker + virtual-param
    allowlist.  Unwrapped specs (``wrap=False``, e.g. ``call_tool``, a
    passthrough proxy) register plainly via ``mcp.tool()`` with no marker.

    Args:
        mcp: The FastMCP server instance to register on.
        specs: The declarative tool specs (one per tool).
    """
    for spec in specs:
        options = spec.tool_options()
        if not spec.wrap:
            mcp.tool(**options)(spec.impl)
            continue

        executor = make_impl_executor(
            spec.impl,
            paginated=spec.paginated,
            limit_max=spec.limit_max,
        )
        register_synthetic_tool(
            mcp,
            executor=executor,
            paginated=spec.paginated,
            limit_max=spec.limit_max,
            virtual_params=spec.virtual_params,
            required_scope=spec.required_scope,
            **options,
        )(spec.impl)


def paginated_output_schema(schema: dict[str, Any]) -> dict[str, Any]:
    """Return *schema* with the standard pagination envelope declared.

    Pagination metadata is placed beside ``result`` in the runtime
    ``structured_content`` envelope, matching autogenerated tool output.
    The input is copied so callers can safely reuse their base schema.
    """
    result = copy.deepcopy(schema)
    properties = result.setdefault("properties", {})
    for name, property_schema in PAGINATION_SCHEMA_PROPERTIES.items():
        properties.setdefault(name, copy.deepcopy(property_schema))
    return result


def _annotation_with_bounds(annotation: Any, extra: dict[str, Any]) -> Any:
    """Return *annotation* with schema-only *extra* bounds appended.

    Additive by contract: every existing metadata item survives.  Pydantic
    merges multiple ``FieldInfo`` items, so the bounds ``Field`` is appended
    rather than replacing the annotation.  String metadata (FastMCP's short
    description form, e.g. ``Annotated[int, "Page number (1-based, default 1)"]``)
    is promoted to ``Field(description=...)`` first — a bare string would
    otherwise be shadowed by the appended ``Field`` and its description lost.
    """
    if get_origin(annotation) is not Annotated:
        return Annotated[annotation, Field(json_schema_extra=dict(extra))]
    base, *metadata = get_args(annotation)
    promoted = [Field(description=item) if isinstance(item, str) else item for item in metadata]
    return Annotated[base, *promoted, Field(json_schema_extra=dict(extra))]


def _annotations_with_pagination_bounds(
    annotations: dict[str, Any],
    limit_max: int,
) -> dict[str, Any]:
    """Return *annotations* with page/limit bounds declared, nothing dropped.

    Mirrors the additive schema augmentation autogen tools receive from
    ``validation.augment_schema_with_validation`` (inject ``minimum`` /
    ``maximum`` without replacing existing schema keys).  FastMCP builds the
    tool's parameter schema from the function annotations at registration
    time; declaring the bounds here makes them machine-readable in the
    schema, so ``tool_info`` and the ``gitea://tool/{name}/schema`` resource
    surface the per-tool page-size maximum to agents instead of a hardcoded
    doc number — matching autogen tools whose ``SCHEMA_CONSTRAINTS`` declare
    ``page.minimum`` / ``per_page.maximum``.

    The bounds are declared via ``Field(json_schema_extra=...)`` —
    schema-only, so pydantic does not enforce them at the MCP boundary.
    ``Field(ge=..., le=...)`` would reject invalid values with a pydantic
    ``ValidationError`` (leaking ``errors.pydantic.dev`` URLs to agents)
    before the executor's friendly ``validate_pagination`` runs.  Schema-only
    declaration keeps the error surface identical to autogen tools: the
    executor rejects with ``"page must be >= 1"`` / ``"limit must be <= N"``.
    """
    result = dict(annotations)
    for param_name, extra in (
        ("page", {"minimum": 1}),
        ("limit", {"minimum": 1, "maximum": limit_max}),
    ):
        if param_name not in result:
            continue
        result[param_name] = _annotation_with_bounds(result[param_name], extra)
    return result


def make_impl_executor(
    impl: Callable[..., Any],
    *,
    paginated: bool = False,
    limit_max: int | None = None,
) -> Executor:
    """Build a synthetic executor that runs *impl* through the contract spine.

    The returned executor receives ``(kwargs, extracted, ctx)`` from the
    shared spine (:func:`~tools.contract.build_transform_fn`):

    1. **Re-supply virtual params** — the spine popped every registry virtual
       param from ``kwargs``; the executor puts back every popped value the
       impl declares.  This covers the generic ``format``/``detail``/
       ``fetch_all`` and any tool-specific param that collides with a
       registry name (e.g. ``tool_info``'s ``detail``).
    2. **Validate pagination** (when *paginated*) — friendly ``page >= 1`` /
       ``limit <= limit_max`` errors, matching autogen.
    3. **Call the impl** with ``ctx`` when declared.
    4. **Mark ``_formatted``** — the impl renders its own output (including
       bespoke markdown extras and formatters), so the shared format
       post-hook must not re-render it.  The marker is set unconditionally:
       an impl is contractually expected to render its own content
       (``apply_format`` / ``format_paginated_result`` / a custom formatter).

    Args:
        impl: The synthetic tool function (full signature — virtual params
            and ``ctx`` included).  Its body performs the real work and
            renders its own output.
        paginated: Validate ``page``/``limit`` before calling *impl*.
        limit_max: Upper bound for ``limit``.  Defaults to ``PAGE_SIZE_MAX``.
    """
    fn_params = inspect.signature(impl).parameters
    effective_limit_max = limit_max if limit_max is not None else PAGE_SIZE_MAX

    async def executor(
        kwargs: dict[str, Any],
        extracted: dict[str, Any] | None,
        ctx: Any | None,
    ) -> ToolResult:
        call_kwargs = dict(kwargs)
        for name, value in (extracted or {}).items():
            if name in fn_params:
                call_kwargs[name] = value
        if paginated:
            validate_pagination(
                call_kwargs.get("page"),
                call_kwargs.get("limit"),
                page_size_name="limit",
                page_size_max=effective_limit_max,
            )
        if "ctx" in fn_params:
            call_kwargs["ctx"] = ctx
        result = cast("ToolResult", await impl(**call_kwargs))
        result.meta = {**(result.meta or {}), "_formatted": True}
        return result

    return executor


def register_synthetic_tool(  # noqa: PLR0913 - six explicit contract knobs are clearer than a kwargs bag
    mcp: Any,
    *,
    executor: Executor,
    paginated: bool = False,
    limit_max: int | None = None,
    virtual_params: set[str] | None = None,
    required_scope: str | None = None,
    **tool_options: Any,
) -> Callable[[Callable[..., Any]], Callable[..., Any]]:
    """Register a synthetic tool on the server-level contract transform.

    Stamps the wrap-me marker (``_contract_wrap``), a serializable
    ``_executor_id`` (the executor itself lives in the server's registry — a
    callable in ``tool.meta`` raises ``PydanticSerializationError``), and the
    tool's virtual-param allowlist into ``tool.meta`` so the server-level
    ``_ToolWrappingTransform`` wraps this tool exactly like an autogenerated
    one: virtual params injected from the registry, validated, and formatted
    through the shared spine.

    Prefer the declarative :func:`register_all_synthetic_tools` +
    :class:`SyntheticToolSpec` at call sites; this lower-level function
    remains the registration primitive.

    Args:
        mcp: The FastMCP server instance to register on.
        executor: The per-tool executor (see :func:`make_impl_executor`).
            Registered in the server's executor registry (released with the
            server) and run by the transform's spine on every call.
        paginated: When True, validate ``page``/``limit`` at runtime and
            declare the pagination envelope in ``output_schema``.
        limit_max: Upper bound for ``limit``.  Defaults to ``PAGE_SIZE_MAX``
            (100); pass a custom value for tools whose documented maximum
            differs (e.g. ``read_doc`` paginates guide lines and allows 200).
            The bound is declared in the tool's parameter schema (as
            ``maximum``) so agents discover it via ``tool_info``.
        virtual_params: Allowlist of virtual params (from the
            :mod:`virtual_params` registry) this tool opts into.  Defaults to
            ``{"format", "detail", "fetch_all"}`` for paginated tools and
            ``{"format", "detail"}`` otherwise.  Tool-specific profiles pass
            their own set (e.g. ``read_doc`` opts into ``format`` only);
            ``sudo`` is opt-in for future API-calling synthetic scripts.
        required_scope: Optional Gitea API scope required to use this tool.
            Stamped in ``tool.meta`` for future scope gating of synthetic
            tools (mirrors ``ResourceMeta.required_scope``); currently no
            synthetic tool declares one.
        **tool_options: Remaining ``mcp.tool()`` options (name, description,
            tags, annotations, output_schema, ...).
    """
    if paginated and "output_schema" in tool_options:
        tool_options["output_schema"] = paginated_output_schema(tool_options["output_schema"])

    effective_limit_max = limit_max if limit_max is not None else PAGE_SIZE_MAX
    default_virtual = {"format", "detail", "fetch_all"} if paginated else {"format", "detail"}
    effective_virtual = virtual_params if virtual_params is not None else default_virtual

    def decorator(function: Callable[..., Any]) -> Callable[..., Any]:
        if paginated:
            # Declare page/limit bounds in the parameter schema so
            # ``tool_info`` surfaces them.  Additive — all existing
            # annotation metadata is preserved, mirroring the autogen path's
            # ``augment_schema_with_validation``.
            function.__annotations__ = _annotations_with_pagination_bounds(
                function.__annotations__, effective_limit_max
            )

        tool_name = tool_options.get("name") or function.__name__
        # Executors cannot live in meta (pydantic serializes it) — store
        # them in the server's registry and carry only a serializable id
        # reference (the unprefixed name, unique within one server).  The
        # registry dies with the server; per-server scoping means the same
        # tool name on two servers never cross-resolves executors.
        get_executor_registry(mcp).register(tool_name, executor)

        meta = {
            "_contract_wrap": True,
            "_synthetic": True,
            "_executor_id": tool_name,
            "_virtual_params": set(effective_virtual),
        }
        if required_scope is not None:
            meta["required_scope"] = required_scope
        tool_options["meta"] = meta
        return cast("Callable[..., Any]", mcp.tool(**tool_options)(function))

    return decorator


