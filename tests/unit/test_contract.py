"""Tests for gitea_mcp_server.tools.contract — the generic contract spine.

The spine (:func:`~gitea_mcp_server.tools.contract.build_transform_fn`) is
shared by autogenerated and synthetic tools.  These tests exercise it with a
recording executor, independent of any specific backend: virtual-param
extraction, pre-hooks, context resolution, ``_raw_schema`` attachment, and
post-hook formatting.
"""

from __future__ import annotations

import base64
from typing import TYPE_CHECKING, Any

import pytest
from fastmcp.tools.base import Tool, ToolResult

from gitea_mcp_server.tools.contract import build_transform_fn
from gitea_mcp_server.tools.result_pipeline import ExecutionResult
from tests.helpers.spec_fixtures import make_openapi_spec

if TYPE_CHECKING:
    from gitea_mcp_server.models import ViewHints


def _make_tool(
    *,
    raw_schema: dict[str, Any] | None = None,
    response_type: str | None = None,
    view_hints: ViewHints | None = None,
) -> Tool:
    """Minimal Tool whose meta optionally carries display pipeline metadata."""
    meta: dict[str, Any] = {}
    if raw_schema is not None:
        meta["output_schema_raw"] = raw_schema
    if response_type is not None:
        meta["response_type"] = response_type
    if view_hints is not None:
        meta["view_hints"] = view_hints
    return Tool(
        name="test_tool",
        description="A test tool.",
        parameters={"properties": {}},
        meta=meta,
    )


class TestBuildTransformFn:
    """Tests for the generic per-call contract spine."""

    @pytest.mark.asyncio
    async def test_executor_receives_popped_kwargs_and_extracted(self) -> None:
        """Virtual params are popped from kwargs and passed to the executor."""
        received: dict[str, Any] = {}

        async def executor(
            kwargs: dict[str, Any],
            extracted: dict[str, Any] | None,
            ctx: Any,
        ) -> ExecutionResult:
            received["kwargs"] = dict(kwargs)
            received["extracted"] = dict(extracted or {})
            return ExecutionResult(data="ok", shape="scalar")

        tool = _make_tool()
        transform_fn = build_transform_fn(tool, executor, default_format="markdown")
        result = await transform_fn(query="q", page=1, format="json", detail="full")

        assert received["kwargs"] == {"query": "q", "page": 1}
        assert received["extracted"] == {"format": "json", "detail": "full"}
        assert result.structured_content == {"result": "ok"}

