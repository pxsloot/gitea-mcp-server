    @pytest.mark.asyncio
    async def test_autogen_allowlist_leaves_fetch_all_in_kwargs(self) -> None:
        """Autogen tools' stamped allowlist excludes fetch_all → rejected as unknown.

        ``_inject_params`` stamps ``tool.meta["_virtual_params"]`` with the
        actually-injected set (fetch_all is predicate-gated to synthetic
        tools), so extraction leaves it in kwargs for validation to reject
        instead of silently dropping it.
        """
        received: dict[str, Any] = {}

        async def executor(
            kwargs: dict[str, Any],
            extracted: dict[str, Any] | None,
            ctx: Any,
        ) -> ExecutionResult:
            received["kwargs"] = dict(kwargs)
            received["extracted"] = dict(extracted or {})
            return ExecutionResult(data="ok", shape="scalar")

        tool = _make_tool()
        # What _inject_params stamps for an autogen tool: visible params that
        # passed injection (format/detail), fetch_all excluded by predicate.
        tool.meta = {"_virtual_params": {"format", "detail"}}
        transform_fn = build_transform_fn(tool, executor, default_format="markdown")
        await transform_fn(query="q", format="json", fetch_all=True)

        assert received["extracted"] == {"format": "json"}
        assert received["kwargs"] == {"query": "q", "fetch_all": True}

    @pytest.mark.asyncio
    async def test_openapi_spec_forwarded_to_render(self, monkeypatch: Any) -> None:
        """build_transform_fn captures openapi_spec and threads it to render (#759).

        The spec enables root-list item summaries under ``detail=concise``.
        This is the unit lock for the closure threading — without it the
        wiring (``mcp_builder`` → ``build_transform_fn`` → ``render`` →
        collapse) is pinned only by the live suite.
        """
        from gitea_mcp_server.tools import contract as contract_module

        spec = make_openapi_spec()
        seen: dict[str, Any] = {}
        real_render = contract_module.render

        def _spy_render(result: ExecutionResult, **kwargs: Any) -> ToolResult:
            seen.update(kwargs)
            return real_render(result, **kwargs)

        monkeypatch.setattr(contract_module, "render", _spy_render)

        async def executor(
            kwargs: dict[str, Any],
            extracted: dict[str, Any] | None,
            ctx: Any,
        ) -> ExecutionResult:
            return ExecutionResult(data="ok", shape="scalar")

        transform_fn = build_transform_fn(
            _make_tool(), executor, openapi_spec=spec, default_format="markdown"
        )
        result = await transform_fn(query="q", format="json")

        assert seen["openapi_spec"] is spec
        assert result.structured_content == {"result": "ok"}

