class TestRegisterAutoGeneratedSkipUri:
    """Tests for skip_uris in auto-generated resources."""

    @pytest.fixture
    def mock_mcp(self) -> MagicMock:
        return MagicMock(spec=FastMCP)

    @pytest.fixture
    def mock_gitea_client(self) -> AsyncMock:
        return AsyncMock()

    async def test_skip_uris_excluded(
        self, mock_mcp: MagicMock, mock_gitea_client: AsyncMock
    ) -> None:
        """Resources with URIs in skip_uris are not registered."""
        spec: OpenAPISpec = {
            "paths": {
                "/repos/{owner}/{repo}": {
                    "get": {
                        "summary": "Get repo",
                        "operationId": "getRepo",
                    }
                }
            }
        }

        register_auto_generated_resources(
            mock_mcp,
            mock_gitea_client,
            spec,
            skip_uris={"gitea://repos/{owner}/{repo}"},
        )

        mock_mcp.resource.assert_not_called()

    async def test_skip_uris_excluded_with_query_suffix(
        self, mock_mcp: MagicMock, mock_gitea_client: AsyncMock
    ) -> None:
        """Resources are skipped even when skip_uris has {?query} suffix.

        Auto-generated resources build URIs without query suffixes
        (e.g. "gitea://repos/{owner}/{repo}/issues"), but custom
        resources register with {?state,type} suffixes.  The skip
        mechanism normalizes by stripping the suffix so the base
        URIs match.
        """
        spec: OpenAPISpec = {
            "paths": {
                "/repos/{owner}/{repo}/issues": {
                    "get": {
                        "summary": "List issues",
                        "operationId": "listIssues",
                    }
                }
            }
        }

        register_auto_generated_resources(
            mock_mcp,
            mock_gitea_client,
            spec,
            skip_uris={"gitea://repos/{owner}/{repo}/issues{?state,type}"},
        )

        mock_mcp.resource.assert_not_called()

    async def test_value_error_during_registration_logged(
        self, mock_mcp: MagicMock, mock_gitea_client: AsyncMock
    ) -> None:
        """ValueError from mcp.resource is caught and logged."""
        mock_mcp.resource = MagicMock(side_effect=ValueError("Duplicate URI"))

        spec: OpenAPISpec = {
            "paths": {
                "/repos/{owner}/{repo}": {
                    "get": {
                        "summary": "Get repo",
                        "operationId": "getRepo",
                    }
                }
            }
        }

        # Should not raise - ValueError is caught
        register_auto_generated_resources(mock_mcp, mock_gitea_client, spec, skip_uris=set())


