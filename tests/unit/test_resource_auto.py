class TestAutoGeneratedResourceErrors:
    """Tests for auto-generated resource error handling."""

    @pytest.fixture
    def mock_mcp(self) -> MagicMock:
        """Create a mock FastMCP instance."""
        return MagicMock(spec=FastMCP)

    @pytest.fixture
    def mock_gitea_client(self) -> AsyncMock:
        """Create a mock GiteaClient."""
        return AsyncMock()

    async def test_404_raises_structured_error(
        self, mock_mcp: MagicMock, mock_gitea_client: AsyncMock
    ) -> None:
        """Test auto-generated resource raises ResourceError with proper structure on 404."""
        spec = make_openapi_spec(
            paths={
                "/test/{id}": {
                    "get": {
                        "summary": "Test endpoint",
                        "operationId": "testEndpoint",
                        "parameters": [
                            {
                                "name": "id",
                                "in": "path",
                                "required": True,
                                "schema": {"type": "string"},
                            }
                        ],
                    }
                }
            }
        )

        # Track registered functions
        registered = []

        def track_decorator(uri: str, **kwargs: Any) -> Callable:
            def decorator(func: Callable) -> Callable:
                registered.append((uri, func))
                return func

            return decorator

        mock_mcp.resource = MagicMock(side_effect=track_decorator)

        register_auto_generated_resources(mock_mcp, mock_gitea_client, spec, skip_uris=set())

        assert len(registered) == 1
        uri, resource_func = registered[0]
        assert uri == "gitea://test/{id}"

        # Simulate 404 error from the real production exception
        mock_gitea_client.request = AsyncMock(
            side_effect=GiteaAPIError("Not Found", status_code=HTTP_STATUS_NOT_FOUND),
        )

        with pytest.raises(ResourceError) as exc_info:
            await resource_func(id="123")

        error_data = exc_info.value.args[0]
        # Auto resources now use the factory's _request_and_wrap which formats
        # the error with the default "Resource not found." message.
        assert error_data["code"] == "NOT_FOUND"
        assert error_data["message"] == "Resource not found."
        assert error_data["resource_type"] == "api"
        assert error_data["resource_id"] == "/test/123"
